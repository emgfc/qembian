#!/usr/bin/env python3
"""Generate kernel/eka/kernel/exec92_map.h from personalities/sym92/exec.map (a personality's exec
numbering: the user side's SWI numbers -> our kernel's exec handlers).

  gen_exec_map.py execs.txt OUT.h sym92=personalities/sym92/exec.map sym91=personalities/sym91/exec.map
  (old form: gen_exec_map.py execs.txt personalities/sym92/exec.map OUT.h)

The header defines, for the 9.2 personality tables built at boot by sexec92.cpp:
  KExec92Fast[n]  n = 9.2 fast number;  >=0 our fast number, or EXEC92_SHIM(k), or EXEC92_INVALID
  KExec92Slow[n]  n = 9.2 slow number;  same encoding with our slow numbers
  EXEC92_SHIMS    X-macro list of shims: X(index, name, kind, base)  kind = FAST | SLOW,
                  base = native exec whose flags a slow shim inherits (or None)
"""
import os, re, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
import exec_table

# old form: execs.txt MAP OUT.h (one personality, sym92); new form: execs.txt OUT.h NAME=MAP...
# (every personality's tables in one header; shims and logging stubs shared). NAME symN -> tag N.
args = sys.argv[1:]
if len(args) == 3 and '=' not in args[1]:
    execs, out, maps = args[0], args[2], [('sym92', args[1])]
else:
    execs, out, maps = args[0], args[1], [a.split('=', 1) for a in args[2:]]
ours = exec_table.ours(execs)
num = {v: k for k, v in ours.items()}
shims = []
tables = []
for pname, mapf in maps:
    fast, slow = {}, {}
    for line in open(mapf):
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        n, name = line.split()[:2]
        kind, idx = ('FAST', int(n[1:], 16)) if n[0] == 'F' else ('SLOW', int(n[1:], 16))
        tab = fast if kind == 'FAST' else slow
        if name == '!invalid':
            v = 'EXEC92_INVALID'
        elif name.startswith('@'):
            sname, _, base = name[1:].partition(':')
            if base and base not in num:
                raise SystemExit('%s %s: unknown base exec %s' % (pname, n, base))
            if sname not in [x[1] for x in shims]:
                shims.append((len(shims), sname, kind, base or 'None'))
            v = 'EXEC92_SHIM(%d)' % [x[1] for x in shims].index(sname)
        else:
            o = num[name]
            if bool(o & 0x800000) != (kind == 'FAST'):
                raise SystemExit('%s %s: %s is a %s exec in our kernel' % (pname, n, name, 'fast' if o & 0x800000 else 'slow'))
            v = '%d' % (o & 0xFFFF)
        tab[idx] = (v, name)
    nf, ns = max(fast) + 1, max(slow) + 1
    assert sorted(fast) == list(range(nf)) and sorted(slow) == list(range(ns)), pname
    tables.append((re.sub(r'\D', '', pname), mapf, fast, slow, nf, ns))
with open(out, 'w') as f:
    f.write('// GENERATED by tools/personality/gen_exec_map.py from %s - do not edit\n'
            % ', '.join(m for _, m in maps))
    f.write('// Executive call numberings of the personalities (personalities/<name>/exec.map) -> this kernel\n\n')
    f.write('#define EXEC92_INVALID (-1)\n#define EXEC92_SHIM(k) (-2-(k))\n')
    f.write('#define EXEC92_MAX_FAST %d\n#define EXEC92_MAX_SLOW %d\n\n' % (max(t[4] for t in tables), max(t[5] for t in tables)))
    f.write('#define EXEC92_SHIMS(X) \\\n%s\n\n' % ' \\\n'.join('\tX(%d, %s, %s, %s)' % x for x in shims))
    for nm, which in (('FAST', 2), ('SLOW', 3)):
        bad = sorted({i for t in tables for i in range(t[4 if which == 2 else 5]) if t[which][i][0] == 'EXEC92_INVALID'})
        f.write('#define EXEC92_BAD_%s(X) %s\n' % (nm, ' '.join('X(0x%02x)' % b for b in bad)))
    f.write('\n')
    for tag, mapf, fast, slow, nf, ns in tables:
        f.write('// %s\n#define EXEC%s_FAST_COUNT %d\n#define EXEC%s_SLOW_COUNT %d\n' % (mapf, tag, nf, tag, ns))
        for nm, tab, cnt in (('Fast', fast, nf), ('Slow', slow, ns)):
            f.write('static const TInt16 KExec%s%s[%d] =\n\t{\n' % (tag, nm, cnt))
            for i in range(cnt):
                f.write('\t%-16s // %s%02x %s\n' % (tab[i][0] + ',', nm[0], i, tab[i][1]))
            f.write('\t};\n\n')
print('; '.join('sym%s fast %d, slow %d' % (t[0], t[4], t[5]) for t in tables) + '; shims ' + ', '.join(x[1] for x in shims))
