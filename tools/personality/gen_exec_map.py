#!/usr/bin/env python3
"""Generate kernel/eka/kernel/exec92_map.h from personalities/sym92/exec.map (a personality's exec
numbering: the user side's SWI numbers -> our kernel's exec handlers).

  gen_exec_map.py execs.txt personalities/sym92/exec.map OUT.h

The header defines, for the 9.2 personality tables built at boot by sexec92.cpp:
  KExec92Fast[n]  n = 9.2 fast number;  >=0 our fast number, or EXEC92_SHIM(k), or EXEC92_INVALID
  KExec92Slow[n]  n = 9.2 slow number;  same encoding with our slow numbers
  EXEC92_SHIMS    X-macro list of shims: X(index, name, kind, base)  kind = FAST | SLOW,
                  base = native exec whose flags a slow shim inherits (or None)
"""
import os, re, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
import exec_table

execs, mapf, out = sys.argv[1:4]
ours = exec_table.ours(execs)
num = {v: k for k, v in ours.items()}
fast, slow, shims = {}, {}, []
for line in open(mapf):
    line = line.split('#', 1)[0].strip()
    if not line:
        continue
    n, name = line.split()[:2]
    kind, idx = ('FAST', int(n[1:], 16)) if n[0] == 'F' else ('SLOW', int(n[1:], 16))
    tab = fast if kind == 'FAST' else slow
    if name == '!invalid':
        v = 'EXEC92_INVALID'
    elif name.startswith('@'):
        s, _, base = name[1:].partition(':')
        if base and base not in num:
            raise SystemExit('%s: unknown base exec %s' % (n, base))
        if s not in [x[1] for x in shims]:
            shims.append((len(shims), s, kind, base or 'None'))
        v = 'EXEC92_SHIM(%d)' % [x[1] for x in shims].index(s)
    else:
        o = num[name]
        if bool(o & 0x800000) != (kind == 'FAST'):
            raise SystemExit('%s: %s is a %s exec in our kernel' % (n, name, 'fast' if o & 0x800000 else 'slow'))
        v = '%d' % (o & 0xFFFF)
    tab[idx] = (v, name)
nf, ns = max(fast) + 1, max(slow) + 1
assert sorted(fast) == list(range(nf)) and sorted(slow) == list(range(ns))
with open(out, 'w') as f:
    f.write('// GENERATED by tools/personality/gen_exec_map.py from personalities/sym92/exec2.map - do not edit\n')
    f.write('// Symbian 9.2 executive call numbering (Nokia N95 8GB EUSER) -> this kernel\n\n')
    f.write('#define EXEC92_FAST_COUNT %d\n#define EXEC92_SLOW_COUNT %d\n' % (nf, ns))
    f.write('#define EXEC92_INVALID (-1)\n#define EXEC92_SHIM(k) (-2-(k))\n\n')
    f.write('#define EXEC92_SHIMS(X) \\\n%s\n\n' % ' \\\n'.join('\tX(%d, %s, %s, %s)' % s for s in shims))
    for nm, tab, cnt in (('FAST', fast, nf), ('SLOW', slow, ns)):
        bad = ['0x%02x' % i for i in range(cnt) if tab[i][0] == 'EXEC92_INVALID']
        f.write('#define EXEC92_BAD_%s(X) %s\n' % (nm, ' '.join('X(%s)' % b for b in bad)))
    f.write('\n')
    for nm, tab, cnt in (('Fast', fast, nf), ('Slow', slow, ns)):
        f.write('static const TInt16 KExec92%s[%d] =\n\t{\n' % (nm, cnt))
        for i in range(cnt):
            f.write('\t%-16s // %s%02x %s\n' % (tab[i][0] + ',', nm[0], i, tab[i][1]))
        f.write('\t};\n\n')
print('fast %d, slow %d, shims %s' % (nf, ns, ', '.join(s[1] for s in shims)))
