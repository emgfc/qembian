#!/usr/bin/env python3
"""Glue for ROM blobs (raw code at a fixed ROM address, e.g. src/gcebe): imports and XIP rebinds.

  blob_glue.py imports --list FILE --asm OUT.S --header OUT.h [--prefix ROM]
      FILE lines: <macro> <module> <mangled export name | ordinal>. Each import becomes a veneer named
      by the mangled symbol (by ordinal: <module>_ord<N>) ("ldr pc,[pc,#-4]; .word <export address>") and <PREFIX>_<macro> = address in
      the header. Addresses come from the device's syb_sym index (build/roms/<id>/<fw>/symindex.json).
  blob_glue.py rebind --elf BLOB.elf --out PATCHES.txt MODULE:ORD=SYMBOL[@IMPORTER,...] ...
      Every XIP import thunk in the core image ("ldr pc,[pc,#-4]; .word A", A = export ORD of MODULE)
      gets A replaced by SYMBOL's address in the linked blob, in all importers or only the listed
      ones. Output: tools/romcompose.py --patches lines (ADDR ORIGINAL NEW, bytes in memory order).
Device: $SYBORG_DEVICE / the registry default (tools/device.py).
"""
import argparse, json, os, struct, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import device as devmodel
import syb_sym

B = 0x80000000


def index():
    syb_sym.Rom()                       # builds or refreshes the index when needed
    j = json.load(open(syb_sym.IDX))
    return {m['name'].lower(): m for m in j['modules']}


def export(mods, module, key):
    m = mods.get(module.lower())
    if not m:
        raise SystemExit('blob_glue: no module %s in the ROM index' % module)
    for e in m['exports']:
        if e[0] == key or e[2] == key:
            return e
    raise SystemExit('blob_glue: %s has no export %s' % (module, key))


def cmd_imports(a):
    mods = index()
    rows = []
    for ln in open(a.list):
        ln = ln.split('#', 1)[0].split()
        if not ln:
            continue
        macro, module, sym = ln[:3]
        e = export(mods, module, int(sym) if sym.isdigit() else sym)
        if sym.isdigit():               # by ordinal: the veneer is <module>_ord<N>
            sym = '%s_ord%s' % (os.path.splitext(module)[0], sym)
        rows.append((macro, module, sym, e[1]))
    with open(a.asm, 'w') as f:
        f.write('@ Generated by tools/blob_glue.py from %s: veneers to ROM exports\n\t.text\n\t.arm\n' % a.list)
        for macro, module, sym, addr in rows:
            f.write('\t.global %s\n\t.type %s, %%function\n\t.align 2\n%s:\n\tldr\tpc, [pc, #-4]\n\t.word\t0x%08x\t@ %s\n'
                    % (sym, sym, sym, addr, module))
    with open(a.header, 'w') as f:
        f.write('/* Generated by tools/blob_glue.py from %s */\n#pragma once\n' % a.list)
        for macro, module, sym, addr in rows:
            f.write('#define %s_%s 0x%08xu  /* %s %s */\n' % (a.prefix, macro, addr, module, sym))
    print('blob_glue: %d imports' % len(rows))


def cmd_rebind(a):
    mods = index()
    img = open(syb_sym.IMG, 'rb').read()
    nm = subprocess.run([os.path.expanduser(os.environ.get('GCC14', '~/gcc-builds/gcc-14.2.0'))
                         + '/bin/arm-none-symbianelf-nm', a.elf], capture_output=True, text=True, check=True).stdout
    syms = {l.split()[2]: int(l.split()[0], 16) for l in nm.splitlines() if len(l.split()) == 3}
    out = ['# Generated by tools/blob_glue.py rebind (%s) - do not edit' % os.path.relpath(a.elf, ROOT)]
    for spec in a.binds:
        lhs, _, sym = spec.partition('=')
        sym, _, only = sym.partition('@')
        module, _, ordn = lhs.partition(':')
        target = export(mods, module, int(ordn))[1]
        if sym not in syms:
            raise SystemExit('blob_glue: %s not in %s' % (sym, a.elf))
        new = syms[sym]
        importers = {x.lower() for x in only.split(',')} if only else None
        n = 0
        for m in mods.values():
            if importers is not None and m['name'].lower() not in importers:
                continue
            for k, v in m['thunks'].items():
                if v != target:
                    continue
                at = int(k) + 4                      # the literal after "ldr pc,[pc,#-4]"
                old = struct.unpack_from('<I', img, at - B)[0]
                assert old == target, (m['name'], hex(at))
                out.append('%08x  %s  %s   # %s: %s ord %s -> blob %s' % (
                    at, struct.pack('<I', old).hex(), struct.pack('<I', new).hex(), m['name'], module, ordn, sym))
                n += 1
        if not n:
            raise SystemExit('blob_glue: no XIP thunk for %s ord %s%s' % (module, ordn, ' in ' + only if only else ''))
    open(a.out, 'w').write('\n'.join(out) + '\n')
    print('blob_glue: %d rebind patches -> %s' % (len(out) - 1, a.out))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    sub = ap.add_subparsers(dest='cmd', required=True)
    p = sub.add_parser('imports')
    p.add_argument('--list', required=True); p.add_argument('--asm', required=True)
    p.add_argument('--header', required=True); p.add_argument('--prefix', default='ROM')
    p = sub.add_parser('rebind')
    p.add_argument('--elf', required=True); p.add_argument('--out', required=True)
    p.add_argument('binds', nargs='+')
    a = ap.parse_args()
    {'imports': cmd_imports, 'rebind': cmd_rebind}[a.cmd](a)


if __name__ == '__main__':
    main()
