#!/usr/bin/env python3
"""ISI helper: names, log decoding, and the fake modem's reply table (the device's [modem].db,
models/<id>/isi-replies.txt, names in platform/isi/names.txt; $SYBORG_DEVICE or the registry default).

  isi.py name RES MSG                  e.g. isi.py name 09 1d
  isi.py log SERIAL.LOG [--all]        annotate ISCPEER send/deliver lines; summary of unanswered
                                       requests per (resource, message, channel)
  isi.py gen-table OUT                 the QEMU modem's reply table (tools/device.py qemu-args writes it)
  isi.py lint                          every device's reply layering: a device reply that repeats the
                                       shared table (redundant) or overrides it (a declared conflict)
"""
import os, re, sys, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import device as devmodel   # tools/device.py
_DEV = devmodel.load()
NAMES = os.path.join(ROOT, devmodel.get(_DEV, 'modem.names', 'platform/isi/names.txt'))   # shared BB5 names
# reply tables, layered: [modem].replies is a file or a list of files (a path with a '/' is relative to
# the repository, else to the device directory); a later file's reply for the same (resource, request)
# replaces an earlier one, so a device file overrides the family's shared table
def dbs_of(prof):
    r = devmodel.get(prof, 'modem.replies', 'isi-replies.txt')
    return [os.path.join(ROOT, x) if '/' in x else devmodel.device_file(prof, x) for x in (r if isinstance(r, list) else [r])]


DBS = dbs_of(_DEV)
DB = DBS[-1]


def load(dbs=None):
    res, msg, replies = {}, {}, []
    for ln in [l for p in [NAMES] + (dbs or DBS) for l in open(p)]:
        body, _, comment = ln.partition('#')
        f = body.split()
        if not f:
            continue
        if f[0] == 'res':
            res[int(f[1], 16)] = (f[2], f[3] if len(f) > 3 else '')
        elif f[0] == 'msg':
            msg[(int(f[1], 16), int(f[2], 16))] = (f[3], f[4] if len(f) > 4 else '')
        elif f[0] == 'reply':
            r, q, p = (int(x, 16) for x in f[1:4])
            rest = f[4:]
            ln_ = None
            if rest and rest[0].startswith('len='):
                ln_ = int(rest[0][4:]); rest = rest[1:]
            data = [int(x, 16) for x in rest]
            replies = [x for x in replies if (x[0], x[1]) != (r, q)]	# later layer wins
            replies.append((r, q, p, ln_ or len(data), data, comment.strip()))
    return res, msg, replies


def name(res, msg, r, m):
    rn = res.get(r, ('RES_%02X' % r, ''))[0]
    if (r, m) in msg:
        return '%s/%s' % (rn, msg[(r, m)][0])
    if (r, m - 1) in msg and msg[(r, m - 1)][0].endswith('_REQ'):
        return '%s/%s' % (rn, msg[(r, m - 1)][0][:-4] + '_RESP')
    return '%s/msg %02X' % (rn, m)


LINE = re.compile(r'ISCPEER: ch (\d+) (send|deliver) \((\d+)\): ((?:[0-9a-f]{2} ?)+)')


def cmd_log(path, show_all):
    res, msg, _ = load()
    sent = collections.OrderedDict()
    answered = set()
    for ln in open(path, errors='replace'):
        m = LINE.search(ln)
        if m:
            ch, kind = int(m.group(1)), m.group(2)
            b = [int(x, 16) for x in m.group(4).split()]
            if len(b) < 10:
                continue
            r, tid, mid = b[3], b[8], b[9]
            nm = name(res, msg, r, mid)
            if show_all:
                print('ch %-2d %-7s %-40s %s' % (ch, kind, nm, ' '.join('%02x' % x for x in b[10:24])))
            if kind == 'send':
                sent[(ch, r, tid)] = (mid, nm)
            else:
                answered.add((ch, r, tid))
        elif 'no reply for resource' in ln and show_all:
            print('   ' + ln.strip())
    un = collections.Counter()
    for k, (mid, nm) in sent.items():
        if k not in answered:
            un[(k[0], nm)] += 1
    print('# unanswered ISI requests (channel, message): %d kinds' % len(un))
    for (ch, nm), c in sorted(un.items()):
        print('  ch %-2d %-45s x%d' % (ch, nm, c))


def table_text(prof):
    """the runtime reply table of a device for the QEMU modem (syborg-modem.replies; tools/device.py
    qemu-args writes it at every launch): "RR QQ PP LEN DATA.." in hex, one reply per line"""
    dbs = dbs_of(prof)
    _, _, replies = load(dbs)
    lines = ['# %s: generated by tools/isi.py from %s -- do not edit' % (prof['_id'], ', '.join(os.path.relpath(d, ROOT) for d in dbs))]
    for r, q, p, n, data, comment in replies:
        if n > 64 or len(data) > 64:
            raise SystemExit('reply %02x %02x too long' % (r, q))
        lines.append(' '.join('%02X' % x for x in [r, q, p, n] + list(data)) + ('  # ' + comment if comment else ''))
    return '\n'.join(lines) + '\n'


def _replies_of(path):
    out = {}
    for ln in open(path):
        f = ln.partition('#')[0].split()
        if f and f[0] == 'reply':
            r, q, p = (int(x, 16) for x in f[1:4])
            rest = f[4:]
            n = int(rest[0][4:]) if rest and rest[0].startswith('len=') else None
            data = tuple(int(x, 16) for x in rest[1:] if n is not None) if n is not None else tuple(int(x, 16) for x in rest)
            key = (r, q)
            out.setdefault(key, []).append((p, n, data))
    return out


def cmd_lint():
    """per device: replies in its own file that repeat or override the shared layers"""
    bad = 0
    for dev in devmodel.device_ids():
        prof = devmodel.load(dev)
        rs = devmodel.get(prof, 'modem.replies', 'isi-replies.txt')
        files = [os.path.join(ROOT, r) if '/' in r else devmodel.device_file(prof, r) for r in (rs if isinstance(rs, list) else [rs])]
        seen = {}
        for f in files:
            own = _replies_of(f)
            for key, vals in own.items():
                if len(vals) > 1:
                    print('%s: %s: %02X %02X given %d times' % (dev, os.path.relpath(f, ROOT), key[0], key[1], len(vals))); bad += 1
                v = vals[-1]
                if key in seen:
                    kind = 'repeats' if seen[key][1] == v else 'overrides'
                    print('%s: %s %s %02X %02X of %s' % (dev, os.path.relpath(f, ROOT), kind, key[0], key[1], seen[key][0]))
                    bad += kind == 'repeats'
                seen[key] = (os.path.relpath(f, ROOT), v)
    print('isi lint: %s' % ('ok' if not bad else '%d problem(s)' % bad))
    return bad


def main():
    a = sys.argv[1:]
    if not a or a[0] in ('-h', '--help'):
        print(__doc__); return
    if a[0] == 'name':
        res, msg, _ = load()
        print(name(res, msg, int(a[1], 16), int(a[2], 16)))
    elif a[0] == 'log':
        cmd_log(a[1], '--all' in a)
    elif a[0] == 'gen-table':
        open(a[1], 'w').write(table_text(_DEV))
    elif a[0] == 'lint':
        sys.exit(1 if cmd_lint() else 0)
    else:
        print(__doc__)


if __name__ == '__main__':
    main()
