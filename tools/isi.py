#!/usr/bin/env python3
"""ISI helper: names, log decoding, and the fake modem's reply table (src/n95compat/isi/isi-db.txt).

  isi.py name RES MSG                  e.g. isi.py name 09 1d
  isi.py log SERIAL.LOG [--all]        annotate ISCPEER send/deliver lines; summary of unanswered
                                       requests per (resource, message, channel)
  isi.py gen-header OUT.h              C table for iscpeer.inl (used by scripts/build-n95compat.sh)
"""
import os, re, sys, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB = os.path.join(ROOT, 'src', 'n95compat', 'isi', 'isi-db.txt')


def load():
    res, msg, replies = {}, {}, []
    for ln in open(DB):
        body, _, comment = ln.partition('#')
        f = body.split()
        if not f:
            continue
        if f[0] == 'res':
            res[int(f[1], 16)] = (f[2], f[3] if len(f) > 3 else '')
        elif f[0] == 'msg':
            msg[(int(f[1], 16), int(f[2], 16))] = (f[3], f[4] if len(f) > 4 else '')
        elif f[0] == 'reply':
            r, q, p = (int(x, 16) for x in f[1:4])
            rest = f[4:]
            ln_ = None
            if rest and rest[0].startswith('len='):
                ln_ = int(rest[0][4:]); rest = rest[1:]
            data = [int(x, 16) for x in rest]
            replies.append((r, q, p, ln_ or len(data), data, comment.strip()))
    return res, msg, replies


def name(res, msg, r, m):
    rn = res.get(r, ('RES_%02X' % r, ''))[0]
    if (r, m) in msg:
        return '%s/%s' % (rn, msg[(r, m)][0])
    if (r, m - 1) in msg and msg[(r, m - 1)][0].endswith('_REQ'):
        return '%s/%s' % (rn, msg[(r, m - 1)][0][:-4] + '_RESP')
    return '%s/msg %02X' % (rn, m)


LINE = re.compile(r'ISCPEER: ch (\d+) (send|deliver) \((\d+)\): ((?:[0-9a-f]{2} ?)+)')


def cmd_log(path, show_all):
    res, msg, _ = load()
    sent = collections.OrderedDict()
    answered = set()
    for ln in open(path, errors='replace'):
        m = LINE.search(ln)
        if m:
            ch, kind = int(m.group(1)), m.group(2)
            b = [int(x, 16) for x in m.group(4).split()]
            if len(b) < 10:
                continue
            r, tid, mid = b[3], b[8], b[9]
            nm = name(res, msg, r, mid)
            if show_all:
                print('ch %-2d %-7s %-40s %s' % (ch, kind, nm, ' '.join('%02x' % x for x in b[10:24])))
            if kind == 'send':
                sent[(ch, r, tid)] = (mid, nm)
            else:
                answered.add((ch, r, tid))
        elif 'no reply for resource' in ln and show_all:
            print('   ' + ln.strip())
    un = collections.Counter()
    for k, (mid, nm) in sent.items():
        if k not in answered:
            un[(k[0], nm)] += 1
    print('# unanswered ISI requests (channel, message): %d kinds' % len(un))
    for (ch, nm), c in sorted(un.items()):
        print('  ch %-2d %-45s x%d' % (ch, nm, c))


def cmd_gen(out):
    res, msg, replies = load()
    lines = ['// Generated by tools/isi.py from src/n95compat/isi/isi-db.txt -- do not edit.',
             'struct SIsiReply { TUint8 iRes, iReq, iResp; TUint8 iLen; TUint8 iData[32]; };',
             'static const SIsiReply KIsiReplies[] =', '\t{']
    for r, q, p, n, data, comment in replies:
        if n > 32 or len(data) > 32:
            raise SystemExit('reply %02x %02x too long' % (r, q))
        lines.append('\t{ 0x%02X, 0x%02X, 0x%02X, %d, { %s } },\t// %s' % (
            r, q, p, n, ', '.join('0x%02X' % x for x in data) or '0', comment or name(res, msg, r, q)))
    lines += ['\t};', '']
    open(out, 'w').write('\n'.join(lines))
    print('%s: %d replies' % (out, len(replies)))


def main():
    a = sys.argv[1:]
    if not a or a[0] in ('-h', '--help'):
        print(__doc__); return
    if a[0] == 'name':
        res, msg, _ = load()
        print(name(res, msg, int(a[1], 16), int(a[2], 16)))
    elif a[0] == 'log':
        cmd_log(a[1], '--all' in a)
    elif a[0] == 'gen-header':
        cmd_gen(a[1])
    else:
        print(__doc__)


if __name__ == '__main__':
    main()
