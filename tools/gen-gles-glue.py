#!/usr/bin/env python3
"""Generate the glue between the N95's libgles_cm.dll and our GLES/EGL blob (docs/gpu-roadmap.md).

  gen-gles-glue.py --blob-addr 0x80320000 --patches models/<id>/gl/gles-patches.txt --asm OUT.S --names OUT.c

Inputs: src/sygl/libgles_cm.ordinals (ordinal -> name, from the SDK's libgles_cm.dso),
<build dir>/core-flat.img + <build dir>/symindex.json (tools/device.py paths dir) (export addresses of the ROM's libgles_cm.dll).

  patches  one ARM "b BLOB+4*(ord-1)" over the first word of each of the 175 libgles_cm entry points
           (romcompose.py --patches format; the original word is verified at compose time). The
           patches depend only on the blob address, not on the blob's contents.
  asm      the blob's entry table: entry ord-1 at BLOB+4*(ord-1) is "b sy_<name>". Every sy_<name>
           is a weak alias of a stub that calls sygl_unimpl(ord) (logs, returns 0), so the C code
           overrides an entry just by defining sy_<name> with the API's signature.
  names    const char* const sygl_names[176] for log messages (read-only data).
  imports  n95imports.h: N95_<macro> = absolute address of an N95 export (from src/sygl/n95imports.txt:
           "<macro> <module> <mangled name>"), called through function pointers (Thumb bit kept).
  imports-asm  one veneer per import, named by its mangled symbol ("ldr pc,[pc,#-4]; .word addr",
           interworking), so C++ code compiled against the SDK headers links to the ROM directly.
"""
import argparse, json, os, struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
B = 0x80000000


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--blob-addr', type=lambda x: int(x, 0), required=True)
    # src/sygl/build.sh passes the device's files (models/<id>/gl/, tools/device.py paths dir)
    ap.add_argument('--ordinals', required=True)
    ap.add_argument('--img', required=True)
    ap.add_argument('--symindex', required=True)
    ap.add_argument('--patches')
    ap.add_argument('--asm')
    ap.add_argument('--names')
    ap.add_argument('--imports-list', required=True)
    ap.add_argument('--imports')
    ap.add_argument('--imports-asm')
    a = ap.parse_args()

    names = {}
    for ln in open(a.ordinals):
        if ln.split():
            o, n = ln.split()[:2]
            names[int(o)] = n
    assert sorted(names) == list(range(1, len(names) + 1)), 'ordinal gaps'
    mods = json.load(open(a.symindex))['modules']
    lib = [m for m in mods if m['name'].lower() == 'libgles_cm.dll']
    assert len(lib) == 1, 'libgles_cm.dll not in symindex'
    addr = {e[0]: e[1] for e in lib[0]['exports']}
    assert sorted(addr) == sorted(names), 'ROM export count %d != SDK ordinals %d' % (len(addr), len(names))
    img = open(a.img, 'rb').read()

    if a.patches:
        with open(a.patches, 'w') as f:
            f.write('# Generated by tools/gen-gles-glue.py (do not edit). Hack H-gles-trampolines\n'
                    '# (docs/hacks.md): every libgles_cm.dll entry point branches to our GLES/EGL blob\n'
                    '# (src/sygl, entry table at 0x%08x, one 4-byte slot per ordinal).\n' % a.blob_addr)
            for o in sorted(names):
                at = addr[o]
                assert not at & 3, 'Thumb or unaligned entry %d %x' % (o, at)
                target = a.blob_addr + 4 * (o - 1)
                off = (target - (at + 8)) >> 2
                assert -(1 << 23) <= off < (1 << 23), 'branch out of range for %s' % names[o]
                new = struct.pack('<I', 0xEA000000 | (off & 0xFFFFFF))
                orig = img[at - B:at - B + 4]
                f.write('%08x  %s  %s   # libgles_cm %s (ord %d)\n' % (at, orig.hex(), new.hex(), names[o], o))
    if a.asm:
        with open(a.asm, 'w') as f:
            f.write('@ Generated by tools/gen-gles-glue.py: libgles_cm entry table (one slot per ordinal)\n'
                    '\t.arm\n\t.section .text.entry,"ax",%progbits\n\t.global sygl_entry_table\n'
                    'sygl_entry_table:\n')
            for o in sorted(names):
                f.write('\tb\tsy_%s\t@ %d\n' % (names[o], o))
            f.write('\n\t.text\n')
            for o in sorted(names):
                f.write('\t.weak\tsy_%s\n\t.set\tsy_%s, sygl_stub_%d\n'
                        'sygl_stub_%d:\n\tmov\tr0, #%d\n\tb\tsygl_unimpl\n' % (names[o], names[o], o, o, o))
    if a.names:
        with open(a.names, 'w') as f:
            f.write('/* Generated by tools/gen-gles-glue.py */\nconst char* const sygl_names[%d] = {\n\t0,\n'
                    % (len(names) + 1))
            for o in sorted(names):
                f.write('\t"%s",\n' % names[o])
            f.write('};\n')
    bymod = {m['name'].lower(): m for m in mods}
    imports = []
    for ln in open(a.imports_list):
        ln = ln.split('#', 1)[0].split()
        if not ln:
            continue
        macro, mod, sym = ln
        m = bymod.get(mod.lower())
        assert m, 'module %s not in symindex' % mod
        hit = [e for e in m['exports'] if e[2] == sym]
        assert len(hit) == 1, '%s!%s: %d matches' % (mod, sym, len(hit))
        imports.append((macro, mod, sym, hit[0]))
    if a.imports_asm:
        with open(a.imports_asm, 'w') as f:
            f.write('@ Generated by tools/gen-gles-glue.py: veneers to N95 exports (src/sygl/n95imports.txt)\n'
                    '\t.arm\n\t.text\n')
            for macro, mod, sym, e in imports:
                f.write('\t.global\t%s\n\t.type\t%s, %%function\n%s:\t@ %s ord %d\n'
                        '\tldr\tpc, [pc, #-4]\n\t.word\t0x%08x\n' % (sym, sym, sym, mod, e[0], e[1]))
    if a.imports:
        with open(a.imports, 'w') as f:
            f.write('/* Generated by tools/gen-gles-glue.py from src/sygl/n95imports.txt */\n'
                    '#ifndef N95IMPORTS_H\n#define N95IMPORTS_H\n')
            for macro, mod, sym, e in imports:
                f.write('#define N95_%s 0x%08xu\t/* %s ord %d %s */\n' % (macro, e[1], mod, e[0], e[3]))
            f.write('#endif\n')


if __name__ == '__main__':
    main()
