#!/usr/bin/env python3
"""The ROM store (docs/device-model-v2.md 2.2.2): imported firmware by identity, not by hand-made names.

  store.py import PATH... [--label L] [--move]   files, directories or archives -> roms/<RM>/<version>/
  store.py list                                  every firmware the store holds (roms/index.toml)
  store.py show ID                               one firmware's manifest (ID = RM-596/011.012)
  store.py reindex                               rewrite every rom.toml and index.toml from the files
  store.py path ID                               the firmware's directory

Layout: roms/<type code>/<version>[~<label>]/ holds the original flash files with their original names,
package metadata (.vpl .dcp .xml .pcx .ini ...) in package/, and rom.toml, generated from the files
(identify.py) and never edited by hand. A label tells firmwares of one version apart whose files differ
(custom firmware: 111.040.1511~delight-6.7). Archives are expanded into a temporary directory and the
archive is left where it is; a directory outside the store is copied (--move moves it). $QEMBIAN_ROMS
relocates the store.
"""
import argparse, hashlib, os, re, shutil, sys, tempfile

FW = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(FW))
sys.path.insert(0, FW)
import identify as idmod   # tools/fw/identify.py

STORE = os.environ.get('QEMBIAN_ROMS') or os.path.join(ROOT, 'roms')
FLASH_ROLES = ('core', 'rofs2', 'rofs3', 'uda', 'other', 'unreadable')


def sha256(p):
    h = hashlib.sha256()
    with open(p, 'rb') as f:
        for b in iter(lambda: f.read(1 << 20), b''):
            h.update(b)
    return h.hexdigest()


def q(s):
    return '"%s"' % str(s).replace('\\', '\\\\').replace('"', '\\"')


def manifest(rec, files, label, source):
    """rom.toml text for one identified firmware (rec: identify.py record) and its stored files"""
    lines = ['# generated by tools/fw/store.py from the files -- do not edit (store.py reindex rewrites it)',
             'schema = 1', 'type_code = %s' % q(rec['type_code']), 'sw_version = %s' % q(rec['sw_version']),
             'sw_date = %s' % q(rec['date']), 'label = %s' % q(label), 'product = %s' % q(rec.get('product', '')),
             'confidence = %s' % q(rec['confidence']), 'source = %s' % q(source), '']
    for p in sorted(rec['products'], key=lambda p: (p['product_code'], p['vpl'])):
        lines += ['[[products]]'] + ['%s = %s' % (k, q(p[k])) for k in ('product_code', 'description', 'group',
                                                                        'variant_version', 'vpl')] + ['']
    order = {r: i for i, r in enumerate(('core', 'rofs2', 'rofs3', 'uda', 'other', 'unreadable'))}
    for f in sorted(rec['files'], key=lambda f: (order.get(f.get('role'), 9), f['name'])):
        path = files.get(f['name'])
        lines += ['[[files]]', 'role = %s' % q(f.get('role', '')), 'name = %s' % q(f['name'])]
        if f.get('id'):
            lines.append('id = %s' % q(f['id']))
        if f.get('vpl_role'):
            lines.append('vpl_role = %s' % q(f['vpl_role']))
        if f.get('partitions'):
            lines.append('partitions = [%s]' % ', '.join(q(x) for x in f['partitions']))
        if path:
            lines += ['size = %d' % os.path.getsize(path), 'sha256 = %s' % q(sha256(path))]
        if f.get('problem'):
            lines.append('problem = %s' % q(f['problem']))
        lines.append('')
    return '\n'.join(lines)


def fw_id(d):
    rel = os.path.relpath(d, STORE)
    return rel.replace(os.sep, '/')


def entries():
    """the store's firmware directories: roms/<RM>/<version>[~label]/rom.toml"""
    import tomllib
    out = []
    for tc in sorted(os.listdir(STORE)) if os.path.isdir(STORE) else []:
        if not re.match(r'RM-\d+$', tc):
            continue
        for v in sorted(os.listdir(os.path.join(STORE, tc))):
            m = os.path.join(STORE, tc, v, 'rom.toml')
            if os.path.exists(m):
                with open(m, 'rb') as f:
                    out.append((fw_id(os.path.dirname(m)), tomllib.load(f)))
    return out


def write_index():
    lines = ['# generated by tools/fw/store.py: every firmware the store holds -- do not edit', 'schema = 1', '']
    for i, man in entries():
        roles = {}
        for f in man.get('files', []):
            roles.setdefault(f['role'], []).append(f.get('id') or f['name'])
        lines += ['[[firmware]]', 'id = %s' % q(i), 'type_code = %s' % q(man['type_code']),
                  'sw_version = %s' % q(man['sw_version']), 'sw_date = %s' % q(man.get('sw_date', '')),
                  'label = %s' % q(man.get('label', '')),
                  'rofs2 = [%s]' % ', '.join(q(x) for x in roles.get('rofs2', [])),
                  'rofs3 = [%s]' % ', '.join(q(x) for x in roles.get('rofs3', [])),
                  'uda = [%s]' % ', '.join(q(x) for x in roles.get('uda', [])), '']
    os.makedirs(STORE, exist_ok=True)
    open(os.path.join(STORE, 'index.toml'), 'w').write('\n'.join(lines))


def place(rec, label):
    """the store directory for an identified firmware (a new label when the version is taken by other files)"""
    if not rec['type_code'] or not rec['sw_version']:
        raise SystemExit('cannot store files of unknown type code/version: %s' % [f['name'] for f in rec['files']])
    ver = re.sub(r'[^\w.+-]', '_', rec['sw_version'])
    return os.path.join(STORE, rec['type_code'], ver + ('~' + re.sub(r'[^\w.+-]', '_', label) if label else ''))


def import_paths(paths, label='', move=False, source=None):
    tmp = tempfile.mkdtemp(prefix='qembian-import-')
    try:
        dirs = []
        for p in paths:
            if os.path.isfile(p) and p.lower().endswith(idmod.ARCHIVES):
                dirs.append(idmod.expand(p, tmp))
                move_this = True			# the expanded copy is ours to move; the archive stays
            else:
                dirs.append(p)
                move_this = move
        files = idmod.collect(dirs, tmp)
        recs = idmod.identify(dirs)
        done = []
        for rec in recs:
            if not rec['type_code'] or not rec['sw_version']:
                # an extra file no firmware claims (an ENO/loader image of its own version scheme, several
                # cores in one directory): reported and left out, the rest of the archive is stored
                print('skipped (type code/version unknown, no core claims it): %s'
                      % ', '.join(f['name'] for f in rec['files']))
                continue
            dst = place(rec, label)
            if os.path.isdir(dst) and os.listdir(dst):
                have = {e: sha256(os.path.join(dst, e)) for e in os.listdir(dst) if os.path.isfile(os.path.join(dst, e))}
                same = all(have.get(f['name']) == sha256(next(p for p in files if os.path.basename(p) == f['name']))
                           for f in rec['files'] if f['name'] in have)
                if not same:
                    raise SystemExit('%s exists with other files of the same name: import with --label' % fw_id(dst))
            os.makedirs(os.path.join(dst, 'package'), exist_ok=True)
            names = {f['name'] for f in rec['files']}
            base_dirs = {os.path.dirname(p) for p in files if os.path.basename(p) in names}
            stored = {}
            for p in files:
                n = os.path.basename(p)
                if os.path.dirname(p) not in base_dirs:
                    continue			# a file of another firmware in the same archive
                to = os.path.join(dst, n) if n in names else os.path.join(dst, 'package', n)
                if os.path.abspath(p) == os.path.abspath(to):
                    stored[n] = to
                    continue
                if os.path.exists(to):
                    os.remove(to)
                (shutil.move if move_this else shutil.copy2)(p, to)
                stored[n] = to
            if not os.listdir(os.path.join(dst, 'package')):
                os.rmdir(os.path.join(dst, 'package'))
            src = source or ', '.join(os.path.basename(os.path.abspath(p)) for p in paths)
            open(os.path.join(dst, 'rom.toml'), 'w').write(manifest(rec, stored, label, src))
            done.append(dst)
            print('stored %s (%s, %d files)' % (fw_id(dst), rec['confidence'], len(stored)))
        write_index()
        return done
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def reindex():
    import tomllib
    for i, man in entries():
        d = os.path.join(STORE, *i.split('/'))
        recs = idmod.identify([d])
        rec = next((r for r in recs if r['type_code'] == man['type_code'] and r['sw_version'] == man['sw_version']), None)
        if not rec:
            print('%s: the files no longer identify as %s %s' % (i, man['type_code'], man['sw_version']))
            continue
        stored = {n: os.path.join(d, n) for n in os.listdir(d) if os.path.isfile(os.path.join(d, n))}
        open(os.path.join(d, 'rom.toml'), 'w').write(manifest(rec, stored, man.get('label', ''), man.get('source', '')))
        print('reindexed %s' % i)
    write_index()


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    sub = ap.add_subparsers(dest='cmd', required=True)
    p = sub.add_parser('import'); p.add_argument('paths', nargs='+'); p.add_argument('--label', default='')
    p.add_argument('--move', action='store_true'); p.add_argument('--source')
    sub.add_parser('list'); sub.add_parser('reindex')
    p = sub.add_parser('show'); p.add_argument('id')
    p = sub.add_parser('path'); p.add_argument('id')
    a = ap.parse_args()
    if a.cmd == 'import':
        import_paths(a.paths, a.label, a.move, a.source)
    elif a.cmd == 'list':
        for i, man in entries():
            n = {}
            for f in man.get('files', []):
                n[f['role']] = n.get(f['role'], 0) + 1
            print('%-34s %-10s %s' % (i, man.get('sw_date', ''), ' '.join('%s:%d' % kv for kv in sorted(n.items()))))
    elif a.cmd == 'show':
        print(open(os.path.join(STORE, *a.id.split('/'), 'rom.toml')).read())
    elif a.cmd == 'path':
        print(os.path.join(STORE, *a.id.split('/')))
    elif a.cmd == 'reindex':
        reindex()
    return 0


if __name__ == '__main__':
    sys.exit(main())
