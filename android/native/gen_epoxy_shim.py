#!/usr/bin/env python3
"""Android stand-in for libepoxy's headers (android/native/include/epoxy/{gl,egl}.h), generated.

The board code (src/qemu-syborg/hw/arm, src/syvg) includes <epoxy/egl.h> and <epoxy/gl.h>: on the desktop
libepoxy resolves every GL/EGL function. On Android the core OpenGL ES 1.1/3.2 and EGL functions are linked
from the NDK's libGLESv1_CM/libGLESv3/libEGL; the extension functions the board calls (OES/EXT, found by
scanning the sources) are resolved once through eglGetProcAddress by these macros.

  gen_epoxy_shim.py NDK_SYSROOT_INCLUDE OUT_DIR SOURCE_FILES...
"""
import os, re, sys

inc, out, srcs = sys.argv[1], sys.argv[2], sys.argv[3:]
used = set()
for f in srcs:
    used |= set(re.findall(r'\b(gl[A-Z]\w*(?:OES|EXT|KHR|NV))\b', open(f, errors='replace').read()))
pfn = {}
for h in ('GLES/glext.h', 'GLES2/gl2ext.h'):
    for m in re.finditer(r'typedef\s+[^;]*?\(GL_APIENTRYP\s+(PFN\w+PROC)\)', open(os.path.join(inc, h)).read()):
        pfn[m.group(1)] = h
lines = ['/* Generated by android/native/gen_epoxy_shim.py -- do not edit. */',
         '#ifndef SYBORG_ANDROID_EPOXY_GL_H', '#define SYBORG_ANDROID_EPOXY_GL_H',
         '#include <GLES3/gl32.h>', '#include <GLES2/gl2ext.h>', '#include <GLES/gl.h>', '#include <GLES/glext.h>',
         '#include <EGL/egl.h>', '']
missing = []
for n in sorted(used):
    t = 'PFN%sPROC' % n.upper()
    if t not in pfn:
        missing.append(n)
        continue
    lines += ['static inline %s syb_%s(void)' % (t, n), '{',
              '    static %s p;' % t,
              '    if (!p) p = (%s)eglGetProcAddress("%s");' % (t, n),
              '    return p;', '}', '#define %s (syb_%s())' % (n, n)]
lines += ['', '#endif', '']
os.makedirs(os.path.join(out, 'epoxy'), exist_ok=True)
open(os.path.join(out, 'epoxy', 'gl.h'), 'w').write('\n'.join(lines))
open(os.path.join(out, 'epoxy', 'egl.h'), 'w').write('\n'.join([
    '/* Generated by android/native/gen_epoxy_shim.py -- do not edit. */',
    '#ifndef SYBORG_ANDROID_EPOXY_EGL_H', '#define SYBORG_ANDROID_EPOXY_EGL_H',
    '#include <EGL/egl.h>', '#include <EGL/eglext.h>', '#include <string.h>',
    '/* libepoxy: is NAME in the display\'s extension string (whole words) */',
    'static inline int epoxy_has_egl_extension(EGLDisplay dpy, const char *name)', '{',
    '    const char *e = eglQueryString(dpy, EGL_EXTENSIONS), *p;',
    '    size_t n = strlen(name);',
    '    for (p = e; p && (p = strstr(p, name)); p += n) {',
    "        if ((p == e || p[-1] == ' ') && (p[n] == ' ' || p[n] == 0)) return 1;",
    '    }', '    return 0;', '}', '#endif', '']))
print('epoxy shim: %d extension functions%s' % (len(used) - len(missing), ('; NOT in the NDK headers: ' + ' '.join(missing)) if missing else ''))
