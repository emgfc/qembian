#!/usr/bin/env bash
# Assemble the NOS stand-in stub and write it as a C array for the ngage board.
#   src/qemu-ngage/nos-standin/build.sh
# Needs arm-none-symbianelf binutils (~/gcc-builds/gcc-14.2.0/bin or $PATH); the generated
# header is committed, so building QEMU does not need them.
set -euo pipefail
cd "$(dirname "$0")"
T=${CROSS:-$HOME/gcc-builds/gcc-14.2.0/bin/arm-none-symbianelf-}
LOAD=0x5149e4c4          # NOS entry point (virtual), see nos_standin.S
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
"${T}as" -march=armv4t -o "$W/s.o" nos_standin.S
"${T}ld" -Ttext=$LOAD -e _start -o "$W/s.elf" "$W/s.o"
"${T}objcopy" -O binary -j .text "$W/s.elf" "$W/s.bin"
"${T}nm" "$W/s.elf" | awk '$2 == "T" {print $3, $1}' > "$W/syms"
python3 - "$W/s.bin" "$LOAD" "$W/syms" > ../hw/arm/ngage_nos_stub.h <<'PY'
import sys
b = open(sys.argv[1], 'rb').read()
print('/* Generated by src/qemu-ngage/nos-standin/build.sh from nos_standin.S: do not edit. */')
print('#define NGAGE_NOS_STUB_VA %s' % sys.argv[2])
for l in open(sys.argv[3]):
    name, addr = l.split()
    if name != '_start':
        print('#define NGAGE_NOS_SYM_%s 0x%s' % (name, addr))
print('static const uint8_t ngage_nos_stub[%d] = {' % len(b))
for i in range(0, len(b), 16):
    print('    ' + ', '.join('0x%02x' % x for x in b[i:i + 16]) + ',')
print('};')
PY
echo "ngage_nos_stub.h: $(stat -c %s "$W/s.bin") bytes at $LOAD"
