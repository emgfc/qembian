// Hosted EKA2: built-in kernel modules. The phone's ROM (our composed hybrid ROM) holds kernel-side
// modules (variant, extensions, LDDs, PDDs) as ARM images prelinked to the ARM kernel; the hosted kernel
// has its own builds of the same sources linked into it, each with renamed entry points
// (Name_KernelModuleEntry, Name_CreateLogicalDevice / Name_CreatePhysicalDevice) and its static
// constructors in its own section (run when the module starts, as the kernel loader runs a kernel DLL's).
// htest.py generates the table (HostedModules) from its module list. When the kernel meets a ROM image of
// a kernel module (extension chain at boot, a code segment the loader creates), the module of the same
// file name is used instead. Original work for qembian; boot sequence after memmodel/epoc/putils.cpp
// (InitVarExt/InitExt0/StartExtensions, EPL, Nokia).

#include "memmodel.h"
#include <e32rom.h>

struct SHostedModule
	{
	const char* iName;					// ROM file name (ELOCD.LDD)
	TInt (*iEntry)(TInt);				// KernelModuleEntry (may be null: LDD/PDD without one)
	TAny* (*iFactory)();				// ordinal 1: CreateLogicalDevice / CreatePhysicalDevice (or null)
	void (**iCtors)();					// static constructors
	void (**iCtorsEnd)();
	TUint8* iData;						// its .data (section kmoddata_<module>)
	TUint8* iDataEnd;
	TUint8* iBss;						// its .bss (kmodbss_<module>)
	TUint8* iBssEnd;
	};
extern const SHostedModule HostedModules[];			// generated by htest.py
extern const TInt HostedModuleCount;

// A module is loaded while a code segment serves it. As a kernel DLL the ARM kernel loads again after it
// was unloaded, a reloaded module starts with its initial .data, a zeroed .bss and its constructors run
// again. Bug 2026-11-12: built-ins kept their statics across an unload; d_display (freed and reloaded by
// the window server) reused objects its previous instance had deleted.
struct SModuleState { TBool iEverLoaded, iLoaded; TUint8* iPristine; TInt iLoads; };
static SModuleState States[64];

static TBool SameName(const char* a, const TDesC& b)
	{
	TInt i = 0;
	for (; a[i] && i < b.Length(); ++i)
		if ((a[i] | 32) != (TUint8(b[i]) | 32))
			return EFalse;
	return !a[i] && i == b.Length();
	}

extern "C" TAny* malloc(TUint aSize);

static TInt Started(TInt aIndex)
	{
	const SHostedModule& m = HostedModules[aIndex];
	SModuleState& st = States[aIndex];
	if (st.iLoaded)
		return aIndex;
	TInt dataSize = m.iData ? m.iDataEnd - m.iData : 0;
	if (!st.iEverLoaded)
		{
		if (dataSize > 0)
			{
			st.iPristine = (TUint8*)malloc(dataSize);		// host heap: extensions start before the kernel heap
			__NK_ASSERT_ALWAYS(st.iPristine);
			memcpy(st.iPristine, m.iData, dataSize);
			}
		}
	else
		{
		if (dataSize > 0)
			memcpy(m.iData, st.iPristine, dataSize);
		if (m.iBss)
			memclr(m.iBss, m.iBssEnd - m.iBss);
		}
	st.iEverLoaded = st.iLoaded = ETrue;
	++st.iLoads;
	for (void (**c)() = m.iCtors; c && c < m.iCtorsEnd; ++c)
		(*c)();
	return aIndex;
	}

// the code segment serving the module is gone: its next load starts fresh
void HostedModuleUnloaded(TInt aModule)
	{
	if (aModule >= 0 && aModule < HostedModuleCount)
		States[aModule].iLoaded = EFalse;
	}

TInt HostedModuleLoads(TInt aModule)		// tests
	{
	return aModule >= 0 && aModule < HostedModuleCount ? States[aModule].iLoads : 0;
	}

// the built-in module for a file name (root name with extension), or -1
TInt HostedFindModule(const TDesC& aRootName)
	{
	for (TInt i = 0; i < HostedModuleCount; ++i)
		if (SameName(HostedModules[i].iName, aRootName))
			return Started(i);
	return -1;
	}

TInt HostedModuleEntry(TInt aModule, TInt aReason)
	{
	const SHostedModule& m = HostedModules[aModule];
	return m.iEntry ? m.iEntry(aReason) : KErrNone;
	}

TAny* HostedModuleFactory(TInt aModule)
	{
	return HostedModules[aModule].iFactory ? HostedModules[aModule].iFactory() : NULL;
	}

TLinAddr HostedModuleExport(TInt aModule, TInt aOrdinal)
	{
	return aOrdinal == 1 ? (TLinAddr)HostedModules[aModule].iFactory : 0;
	}

// ---- the name of a ROM image: search the ROM directory tree for the entry that points at it ----
static TBool FindIn(const TRomDir& aDir, TLinAddr aImage, TDes& aName, TInt aDepth)
	{
	const TUint8* p = (const TUint8*)&aDir.iEntry;
	const TUint8* end = p + aDir.iSize;
	while (p < end)
		{
		const TRomEntry* e = (const TRomEntry*)p;
		if (e->iAtt & 0x10)	// KEntryAttDir
			{
			if (aDepth < 4 && FindIn(*(const TRomDir*)e->iAddressLin, aImage, aName, aDepth + 1))
				return ETrue;
			}
		else if (e->iAddressLin == aImage)
			{
			aName.SetLength(0);
			for (TInt i = 0; i < e->iNameLength && i < aName.MaxLength(); ++i)
				aName.Append(TChar(e->iName[i << 1]));
			return ETrue;
			}
		p += (_FOFF(TRomEntry, iName) + e->iNameLength * 2 + 3) & ~3;
		}
	return EFalse;
	}

extern TLinAddr HostedRomRootDir();
TBool HostedRomImageName(TLinAddr aImage, TDes& aName)
	{
	TLinAddr root = HostedRomRootDir();
	return root && FindIn(*(const TRomDir*)root, aImage, aName, 0);
	}

// ---- boot: the ROM's extension chain (after memmodel/epoc/putils.cpp) ----
struct SExtEntry { TInt iModule; TInt iPriority; };
static SExtEntry Ext[32];
static TInt ExtCount;

// the ROM header's extension chain: each image that is a built-in module gets VariantInit0 (as the
// phone kernel's InitVarExt(EFalse, InitData)), then ExtensionInit0 (priority from its result)
void HostedRomExtensionsInit0()
	{
	const TRomHeader& rh = Epoc::RomHeader();
	TUint variant = TheSuperPage().iActiveVariant;
	TUint cpu = (variant >> 16) & 0xff, asic = variant >> 24;
	TBuf<64> name;
	for (const TRomEntry* pE = (const TRomEntry*)rh.iExtensionFile; pE; )
		{
		const TRomImageHeader& img = *(const TRomImageHeader*)pE->iAddressLin;
		if (THardwareVariant(img.iHardwareVariant).IsCompatibleWith(cpu, asic, variant))
			{
			if (!HostedRomImageName(pE->iAddressLin, name))
				name.Copy(_L8("?"));
			TInt m = HostedFindModule(name);
			if (m < 0)
				Kern::Printf("HOSTED: ROM extension %S has no hosted build: skipped", &name);
			else
				{
				HostedModuleEntry(m, KModuleEntryReasonVariantInit0);
				TInt r = HostedModuleEntry(m, KModuleEntryReasonExtensionInit0);
				if (r >= KErrNone && ExtCount < 32)
					{
					// priority order (highest first), equal priorities in ROM order
					TInt prio = (TUint8)r, i = ExtCount;
					while (i > 0 && Ext[i - 1].iPriority < prio) { Ext[i] = Ext[i - 1]; --i; }
					Ext[i].iModule = m;
					Ext[i].iPriority = prio;
					++ExtCount;
					__KTRACE_OPT(KBOOT, Kern::Printf("HOSTED: extension %S (priority %d)", &name, prio));
					}
				}
			}
		pE = (const TRomEntry*)img.iNextExtension;
		}
	}

void HostedRomExtensionsInit1()
	{
	for (TInt i = 0; i < ExtCount; ++i)
		{
		TInt r = HostedModuleEntry(Ext[i].iModule, KModuleEntryReasonExtensionInit1);
		if (r != KErrNone)
			{
			Kern::Printf("HOSTED: extension %s Init1 returned %d", HostedModules[Ext[i].iModule].iName, r);
			K::Fault(K::EStartExtensionsFailed);
			}
		}
	}
