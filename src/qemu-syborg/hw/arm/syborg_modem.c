static int modem_post_load(void *opaque, int version_id)
{
    SyborgModemState *s = opaque;
    for (int i = 0; i < MODEM_PORTS; i++) {
        if (s->port[i].head >= MODEM_FIFO || s->port[i].count > MODEM_FIFO) {
            return -EINVAL;
        }
        modem_update_irq(&s->port[i]);
    }
    return 0;
}

