/*
 * Syborg fake modem (qembian): the QEMU device around the modem core (syborg_modem_core.c, shared with
 * the hosted EKA2 board), the BB5 cellular modem's ISI side, on the host.
 *
 * The guest keeps only a thin ISC/ISA channel driver (src/standins/_shared/iscpeer.inl): it forwards
 * what the phone's IscApi sends (ISI messages, indication subscriptions, channel open/close) through
 * this device and delivers what comes back. The answers live here, so a modem change needs no ROM
 * rebuild. Protocol and every reply: docs/devices/nokia-n95-8gb-rm320/n95-isc-isi-protocol*.md,
 * platform/isi/replies-bb5.txt (+ models/<id>/isi-replies.txt), docs/hacks.md (H-modem-*).
 *
 * Two ports, one per guest driver (an IRQ can be bound once): port 0 = NokiaISCDriver channels 0..31 or
 * the Symbian^3 ISA driver's 0..63, port 1 = NokiaISCDriverExtension 32..63. Per port, a 0x2000 window:
 *   0x000 ID (r)          0x004 TX_CHANNEL (w)  0x008 TX_LEN (w)      0x00c TX_GO (w: kind, executes)
 *   0x010 RX_COUNT (r)    0x014 RX_CHANNEL (r)  0x018 RX_LEN (r)      0x01c RX_KIND (r)
 *   0x020 RX_POP (w)      0x024 INT_ENABLE (rw: interrupt while RX_COUNT > 0)
 *   0x1000..0x17ff TX buffer (w)               0x1800..0x1fff RX buffer (r): the head frame
 * TX kinds: 1 send ISI message, 2 subscribe (res, msgid pairs), 3 channel opened, 4 channel closed.
 * RX kinds: 1 deliver ISI message, 2 log line (the guest prints "ISCPEER: <text>" in the serial log).
 * Immediate replies are queued before TX_GO returns, so the guest drains them right after a send (the
 * timing of the former in-guest modem); delayed replies and power events use the virtual clock.
 *
 * Properties: config = the board config string (the board copies syborg-platform.config: modem.imei,
 * modem.simst, modem.ind, modem.power_off_ms, audio.ring_units), replies = the reply table generated by
 * tools/device.py qemu-args ("RR QQ PP LEN DATA.." hex per line).
 *
 * SPDX-License-Identifier: GPL-2.0-or-later
 */
