#!/usr/bin/env python3
"""Export tables and forwarders for src/khr (called by src/khr/build.sh).

  gen_khr.py SDK_DEF_DIR OUTDIR [SYGL_DIR]
  -> OUTDIR/libEGL.def       EGL at the SDK's libegl13u ordinals (2..35), then every OpenVG and VGU
                             function as khr_<name> at ordinals 36.., then (with SYGL_DIR) every OpenGL
                             ES 1.x function as khr_<name> and khr_gles_eglChooseConfig/GetConfigs,
                             ABSENT fillers up to 249 (the phone's libEGL.dll has 249 exports)
     OUTDIR/khr_alias.S      khr_<name>: b <name> inside libEGL (the RI defines the plain VG names,
                             sygl the GL ones as sy_<name>)
     OUTDIR/gl_missing.c     a logged stub per GL function sygl does not have
     OUTDIR/libGLES_CM.def/.S    = the SDK's opengles11u (S60 3rd edition's EGL + GL in one DLL):
                             EGL -> libEGL's EGL (config choice: khr_gles_*), GL -> khr_gl*
     OUTDIR/libGLESv1_CM.def/.S  = the SDK's libglesv1_cm11u -> khr_gl*
     OUTDIR/libOpenVG.def, libOpenVGU.def   = the SDK's libopenvg11u / libopenvgu11u
     OUTDIR/libOpenVG.S, libOpenVGU.S       one forwarder per export: "b khr_<name>" (a libEGL import)
"""
import os, re, sys

sdk, out = sys.argv[1], sys.argv[2]
sygl = sys.argv[3] if len(sys.argv) > 3 else None     # '-': no sygl sources (every GL name is in the alias file)
# OpenGL ES 1.1 on the host (tools/gen-gl1.py's gl1_alias.txt): "name target" for every GL ES 1.1 name
gl1 = {}
if len(sys.argv) > 4:
    for ln in open(sys.argv[4]):
        if ln.split():
            n, t = ln.split()
            gl1[n] = t
EGL_TOTAL = 249


def parse(path):
    """(ordinal, name, absent) per EXPORTS line"""
    rows = []
    for ln in open(path):
        m = re.match(r'\s*(\S+)\s+@\s*(\d+)(.*)', ln)
        if m:
            rows.append((int(m.group(2)), m.group(1), 'ABSENT' in m.group(3)))
    return rows


def write_def(path, rows, total):
    by = {o: (n, a) for o, n, a in rows}
    with open(path, 'w') as f:
        f.write('EXPORTS\n')
        for o in range(1, total + 1):
            n, a = by.get(o, ('_._.absent_export_%d' % o, True))
            f.write('\t%s @ %d NONAME%s\n' % (n, o, ' ABSENT' if a else ''))


egl = [r for r in parse(os.path.join(sdk, 'libegl13u.def')) if not r[2]]
vg = [r for r in parse(os.path.join(sdk, 'libopenvg11u.def')) if not r[2]]
vgu = [r for r in parse(os.path.join(sdk, 'libopenvgu11u.def')) if not r[2]]
nxt = max(o for o, _, _ in egl) + 1
rows = list(egl)
for _, n, _ in vg + vgu:
    rows.append((nxt, 'khr_' + n, False))
    nxt += 1
gl, have = [], set()
if sygl:
    for fn in (os.listdir(sygl) if sygl != '-' else []):
        if fn.endswith('.c'):
            have |= set(re.findall(r'\bsy_(gl[A-Za-z0-9_]+)\s*\([^;{]*\)\s*\{', open(os.path.join(sygl, fn)).read()))
    names = [n for _, n, a in parse(os.path.join(sdk, 'opengles11u.def')) if not a and n.startswith('gl')]
    names += [n for _, n, a in parse(os.path.join(sdk, 'libglesv1_cm11u.def')) if not a and n not in names]
    for n in names:
        rows.append((nxt, 'khr_' + n, False))
        gl.append(n)
        nxt += 1
    for n in ('khr_gles_eglChooseConfig', 'khr_gles_eglGetConfigs'):   # the same EGL (the host's)
        rows.append((nxt, n, False))
        nxt += 1
    # libGLES_CM's EGL entries: a forwarder cannot branch to "eglX" (that is its own export), so libEGL
    # also exports each EGL function as khr_eglX
    for _, n, _ in egl:
        rows.append((nxt, 'khr_' + n, False))
        nxt += 1
    # OpenGL ES 2.0 (src/khr/gl2.c, gl2_gen.c define khr2_<name>)
    gl2 = [n for _, n, a in parse(os.path.join(sdk, 'libglesv2u.def')) if not a]
    for n in gl2:
        rows.append((nxt, 'khr2_' + n, False))
        nxt += 1
write_def(os.path.join(out, 'libEGL.def'), rows, max(EGL_TOTAL, nxt - 1))
with open(os.path.join(out, 'khr_alias.S'), 'w') as f:
    f.write('@ Generated by src/khr/gen_khr.py: libEGL exports the RI\'s OpenVG/VGU under khr_ names\n\t.text\n\t.arm\n')
    for _, n, _ in vg + vgu:
        f.write('\t.global khr_%s\n\t.type khr_%s, %%function\n\t.align 2\nkhr_%s:\n\tb\t%s\n' % (n, n, n, n))
    for _, n, _ in (egl if sygl else []):
        f.write('\t.global khr_%s\n\t.type khr_%s, %%function\n\t.align 2\nkhr_%s:\n\tb\t%s\n' % (n, n, n, n))
    for n in ('ChooseConfig', 'GetConfigs'):
        f.write('\t.global khr_gles_egl%s\n\t.type khr_gles_egl%s, %%function\n\t.align 2\nkhr_gles_egl%s:\n\tb\tegl%s\n' % (n, n, n, n))
    for n in gl:
        tgt = gl1.get(n) or ('sy_' + n if n in have else 'khr_missing_' + n)
        f.write('\t.global khr_%s\n\t.type khr_%s, %%function\n\t.align 2\nkhr_%s:\n\tb\t%s\n' % (n, n, n, tgt))
missing = [n for n in gl if n not in have and n not in gl1]
with open(os.path.join(out, 'gl_missing.c'), 'w') as f:
    f.write('/* Generated by src/khr/gen_khr.py: OpenGL ES functions sygl does not implement yet (logged once,\n'
            '   return 0: GL_FALSE / no object / nothing done) */\n'
            'int sy_rdebug_printf(const char* aFmt, ...) __asm__("_ZN6RDebug6PrintfEPKcz");\n'
            'static unsigned char seen[%d];\n' % max(1, len(missing)))
    for i, n in enumerate(missing):
        f.write('unsigned khr_missing_%s(void) { if (!seen[%d]++) sy_rdebug_printf("SYGL: unimplemented %s"); return 0; }\n'
                % (n, i, n))
EGLNAMES = {n for _, n, _ in egl}
GLES_EGL = {'eglChooseConfig': 'khr_gles_eglChooseConfig', 'eglGetConfigs': 'khr_gles_eglGetConfigs'}
if sygl:
    rows3 = parse(os.path.join(sdk, 'libglesv2u.def'))
    write_def(os.path.join(out, 'libGLESv2.def'), rows3, max(o for o, _, _ in rows3))
    with open(os.path.join(out, 'libGLESv2.S'), 'w') as f:
        f.write('@ Generated by src/khr/gen_khr.py: libGLESv2 -> libEGL.dll (khr2_ exports)\n\t.text\n\t.arm\n')
        for _, n, a in rows3:
            if not a:
                f.write('\t.global %s\n\t.type %s, %%function\n\t.align 2\n%s:\n\tb\tkhr2_%s\n' % (n, n, n, n))
    for lib, src in (('libGLES_CM', 'opengles11u.def'), ('libGLESv1_CM', 'libglesv1_cm11u.def')):
        rows3 = parse(os.path.join(sdk, src))
        write_def(os.path.join(out, lib + '.def'), rows3, max(o for o, _, _ in rows3))
        with open(os.path.join(out, lib + '.S'), 'w') as f:
            f.write('@ Generated by src/khr/gen_khr.py: %s -> libEGL.dll\n\t.text\n\t.arm\n' % lib)
            for _, n, a in rows3:
                if a:
                    continue
                if n.startswith('egl'):
                    if n not in EGLNAMES and n not in GLES_EGL:
                        raise SystemExit('gen_khr: %s exports %s, which libEGL does not have' % (lib, n))
                    tgt = GLES_EGL.get(n, 'khr_' + n)
                else:
                    tgt = 'khr_' + n
                f.write('\t.global %s\n\t.type %s, %%function\n\t.align 2\n%s:\n\tb\t%s\n' % (n, n, n, tgt))
for lib, src, rows2, total in (('libOpenVG', 'libopenvg11u.def', vg, 249), ('libOpenVGU', 'libopenvgu11u.def', vgu, 9)):
    write_def(os.path.join(out, lib + '.def'), parse(os.path.join(sdk, src)), total)
    with open(os.path.join(out, lib + '.S'), 'w') as f:
        f.write('@ Generated by src/khr/gen_khr.py: %s -> libEGL.dll (khr_ exports)\n\t.text\n\t.arm\n' % lib)
        for _, n, _ in rows2:
            f.write('\t.global %s\n\t.type %s, %%function\n\t.align 2\n%s:\n\tb\tkhr_%s\n' % (n, n, n, n))
print('gen_khr: libEGL %d EGL + %d VG + %d VGU + %d GL exports (%d GL not in sygl yet)'
      % (len(egl), len(vg), len(vgu), len(gl), len(missing)))
